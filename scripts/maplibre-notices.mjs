// Writes the MapLibre part of THIRD_PARTY_NOTICES.md (P5 S5f): maplibre-gl and every package of its locked
// dependency tree (package-lock.json; `@types/*` left out, they ship no code), each with its version,
// its licence as the lock states it and the licence text as the package ships it. maplibre-gl's
// prebuilt dist bundles its dependencies, so the whole tree is listed (a package used only by a
// command-line tool of the style spec is listed too: listing more is harmless).
//
// Regenerate after a maplibre-gl update, from a checkout with node_modules installed:
//   node scripts/maplibre-notices.mjs [node_modules dir] > /tmp/maplibre-notices.md
// then replace the text between the two "maplibre-notices" markers in THIRD_PARTY_NOTICES.md with it.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const modules = process.argv[2] ?? 'node_modules';
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8')).packages;
const entry = (name) => lock[`node_modules/${name}`];

const tree = new Map();
(function walk(name) {
  const p = entry(name);
  if (!p) throw new Error(`package-lock.json has no node_modules/${name}`);
  if (tree.has(name)) return;
  tree.set(name, p);
  for (const dep of Object.keys(p.dependencies ?? {})) walk(dep);
})('maplibre-gl');

function licenceText(name) {
  const dir = join(modules, name);
  if (!existsSync(dir)) throw new Error(`${dir} is missing: install node_modules first`);
  const file = readdirSync(dir).sort().find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  if (!file) {
    // A package that ships no licence file (murmurhash-js): the README's "License" section, as written.
    const readme = readdirSync(dir).sort().find((f) => /^readme(\.(md|markdown|txt))?$/i.test(f));
    if (readme) {
      const lines = readFileSync(join(dir, readme), 'utf8').replace(/\r\n?/g, '\n').split('\n');
      const at = lines.findIndex((l) => /^#{1,6}\s*licen[cs]e\b/i.test(l));
      if (at >= 0) {
        const level = lines[at].match(/^#+/)[0].length;
        const end = lines.findIndex((l, i) => i > at && /^#+\s/.test(l) && l.match(/^#+/)[0].length <= level);
        const section = lines.slice(at + 1, end < 0 ? undefined : end).join('\n').trim();
        if (section) return `${section}\n\n(From the package's ${readme}, "${lines[at].replace(/^#+\s*/, '')}"; it ships no licence file.)`;
      }
    }
    // No README section either: the package.json declaration and author.
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
    if (!pkg.license) throw new Error(`${name}: no licence file and no licence in package.json`);
    return `No licence file in the package. Its package.json declares ${pkg.license}${author ? `, author ${author}` : ''}; the ${pkg.license} licence text in this file applies.`;
  }
  return readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n').trim();
}

const names = [...tree.keys()].filter((n) => !n.startsWith('@types/')).sort((a, b) => (a === 'maplibre-gl' ? -1 : b === 'maplibre-gl' ? 1 : a < b ? -1 : a > b ? 1 : 0));
const out = ['<!-- maplibre-notices: generated by scripts/maplibre-notices.mjs; do not edit by hand -->', ''];
out.push('| Package | Version | Licence |', '|---|---|---|');
for (const n of names) out.push(`| \`${n}\` | ${tree.get(n).version} | ${tree.get(n).license ?? 'see text'} |`);
out.push('');
for (const n of names) {
  out.push(`### ${n} ${tree.get(n).version}`, '', '```text', licenceText(n), '```', '');
}
out.push('<!-- /maplibre-notices -->');
process.stdout.write(`${out.join('\n')}\n`);
