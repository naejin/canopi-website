// The vendored Canopi design format and its validator (scripts/vendor/canopi-design-format/), which
// stream S4's .canopi download is checked against (design check A11, BT-9).
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { CANOPI_FILE_SCHEMA, CURRENT_CANOPI_FILE_VERSION } from './vendor/canopi-design-format/canopi-design-format.ts';
import { validate } from './vendor/canopi-design-format/validate.mjs';

test('the vendored format is the app file at 0c425fb07, v9, under its licence header', () => {
  const text = readFileSync(new URL('./vendor/canopi-design-format/canopi-design-format.ts', import.meta.url), 'utf8');
  assert.match(text, /at commit 0c425fb07/);
  assert.match(text, /GNU Affero General Public License/);
  assert.match(text, /\/\/ Generated by `cargo run -p bindings-gen`\. Do not edit by hand\./);
  assert.equal(CURRENT_CANOPI_FILE_VERSION, 9);
});

test('validate reads the keywords the schema uses and rejects an empty document', () => {
  assert.ok(validate(CANOPI_FILE_SCHEMA, {}).length > 0, 'an empty object is not a design');
  const s = { $defs: { P: { type: 'object', required: ['n'], properties: { n: { type: 'integer', format: 'uint32', minimum: 0 } }, additionalProperties: false } }, type: 'array', items: { $ref: '#/$defs/P' } };
  assert.deepEqual(validate(s, [{ n: 1 }]), []);
  assert.equal(validate(s, [{ n: -1 }]).length, 1);
  assert.equal(validate(s, [{}]).length, 1);
  assert.equal(validate(s, [{ n: 1, x: 2 }]).length, 1);
  assert.equal(validate({ oneOf: [{ const: 1 }, { type: 'integer' }] }, 1).length, 1, 'oneOf: exactly one');
  assert.deepEqual(validate({ anyOf: [{ type: 'null' }, { type: 'string' }] }, null), []);
  assert.deepEqual(validate({ type: ['string', 'null'], enum: ['a', null] }, 'a'), []);
});
