// Installs the pinned canopi-climate grid release (src/data/climate-release.json) under
// public/data/climate/<version>-<12 hex of the manifest's sha256>/{tiles,soil,regions}/, where the
// consortium page's reader (src/lib/climate/) fetches single tiles. P5 design check section A; owner
// decision 2026-11-11: the tiles are fetched at build and verified, never committed.
//
//   astro build / npm run build             # runs it first (scripts/climate-integration.mjs)
//   npm run install:climate                 # by hand
//   npm run install:climate -- <grid.tar>   # a local archive (same as CANOPI_CLIMATE_ARCHIVE)
//
// Where the archive comes from, in order:
// - nothing at all when public/data/climate/ already holds the pinned grid (its index names the
//   pinned manifest sha256 and every tile is there with its size);
// - CANOPI_CLIMATE_ARCHIVE, a local tar (offline and dev builds; never copied to the cache);
// - the cache, CANOPI_CLIMATE_CACHE (default node_modules/.cache/canopi-climate/);
// - else one plain fetch of the pinned GitHub release asset (no custom headers), written to the cache.
// Each archive must have the pinned size and sha256 before it is read; anything else (a failed
// download included) fails, so a build never deploys without the tiles.
//
// Then, in order, refused on the first failure (nothing is written then):
// - the tar: regular files and directories only, safe relative paths (no absolute path, `..`, link or
//   device), no entry twice, each file at most MAX_FILE_BYTES (Cloudflare's 25 MiB per asset); only
//   manifest.json, SHA256SUMS, build-report.json, ATTRIBUTION.md and tiles|soil|regions/<tile>.tif.
// - SHA256SUMS: every line `<sha256>  <path>` of that form, each listed file present and matching,
//   every file of the archive listed.
// - manifest.json: the pinned sha256; format canopi-climate-grid, format_version 1, a semver
//   builder_version (the pinned tag carries the same), the grid, the variables with their scales, the
//   slots and the site layers' bands exactly as the reader decodes them (src/lib/climate/model.js);
//   each tile entry a valid name at <dir>/<name>.tif with the file's bytes and sha256; no tile file
//   outside the manifest; each tile's TIFF header the layout and position of its name.
// - the consortium export's grid (src/data/consortium-index.json `climate_grid_manifest_sha256`, the
//   grid its ranges were sampled from): refused when it differs; when the export does not name one
//   yet, a warning, recorded in the index as unchecked.
//
// What it writes (both git-ignored, regenerated by every fresh install):
// - <out>/ (default public/data/climate/): the one version directory, tiles byte for byte (the
//   directory name changes with the manifest, so public/_headers caches the tiles forever). No
//   manifest, sums, attribution or install mark are served.
// - src/data/climate-index.json: the URL base, the tile names, sizes and sha256 per layer, variables
//   and scales, slots, the release (version, built_at, manifest sha256, archive and its sha256), the
//   sources to credit and the consortium check. Build-time readers and the page read it.
// The output is staged in a directory of this run, then renamed into place with the index; it must be
// absent, empty or a previous install (version directories only; the old INSTALLED_BY mark of earlier
// installs is dropped). ensureClimate holds a lock (<staging>/lock, its pid; a dead process's lock is
// taken over), so dev, build and build:browser-test running at once never undo each other's install.
// A download with no byte for STALL_MS (30 s) or taking over TIMEOUT_MS (10 min) is aborted, and the
// build fails. `astro dev` never downloads (allowDownload false): archive or cache only.
